"""
=========================================================
Gold AI Trading System
Indicator Configuration
=========================================================
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class IndicatorConfig:
    """
    Indicator parameters used by the trading system.
    """

    # =====================================================
    # EMA
    # =====================================================

    EMA_FAST: int = 9
    EMA_SLOW: int = 21
    EMA_TREND: int = 200

    # =====================================================
    # RSI
    # =====================================================

    RSI_PERIOD: int = 14
    RSI_OVERBOUGHT: float = 70.0
    RSI_OVERSOLD: float = 30.0

    # =====================================================
    # MACD
    # =====================================================

    MACD_FAST: int = 12
    MACD_SLOW: int = 26
    MACD_SIGNAL: int = 9

    # =====================================================
    # ADX
    # =====================================================

    ADX_PERIOD: int = 14
    ADX_TREND: float = 25.0
    ADX_SIDEWAY: float = 18.0

    # =====================================================
    # ATR
    # =====================================================

    ATR_PERIOD: int = 14

    # =====================================================
    # BOLLINGER BAND
    # =====================================================

    BB_PERIOD: int = 20
    BB_STD: float = 2.0
    BB_DEVIATION = 2.0
    # =====================================================
    # VOLUME
    # =====================================================

    VOLUME_PERIOD: int = 20

    # =====================================================
    # VWAP
    # =====================================================

    VWAP_ENABLE: bool = True

    # =====================================================
    # SUPERTREND
    # =====================================================

    SUPERTREND_PERIOD: int = 10
    SUPERTREND_MULTIPLIER: float = 3.0

    # =====================================================
    # CANDLE
    # =====================================================

    HISTORY_BARS: int = 500
